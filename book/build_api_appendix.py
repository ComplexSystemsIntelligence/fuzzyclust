SYM = {
    "–": "--",
    "—": "---",
    "Ł": r"\L{}",
    "ł": r"\l{}",
    "ö": r"\"{o}",
    "ü": r"\"{u}",
    "é": r"\'{e}",
    "á": r"\'{a}",
    "ő": r"\H{o}",
    "š": r"\v{s}",
    "−": "$-$",
    "×": r"$\times$",
    "≥": r"$\geq$",
    "≤": r"$\leq$",
    "²": r"$^2$",
    "α": r"$\alpha$",
    "β": r"$\beta$",
    "γ": r"$\gamma$",
    "δ": r"$\delta$",
    "η": r"$\eta$",
    "λ": r"$\lambda$",
    "μ": r"$\mu$",
    "σ": r"$\sigma$",
    "ρ": r"$\rho$",
    "→": r"$\to$",
}


def esc(s: str) -> str:
    parts = re.split(r"@@M@@(.*?)@@/M@@", s)
    if len(parts) > 1:
        return "".join("$" + p + "$" if i % 2 else esc(p) for i, p in enumerate(parts))
    s = s.replace("\\", r"\textbackslash{}")
    for ch in "&%$#_{}":
        s = s.replace(ch, "\\" + ch)
    s = s.replace("~", r"\textasciitilde{}").replace("^", r"\textasciicircum{}")
    for k, v in SYM.items():
        s = s.replace(k, v)
    return s.replace("@@E@@", r"\emph{").replace("@@/E@@", "}")


def first_sentence(obj) -> str:
    if not (inspect.isclass(obj) or callable(obj)):
        return ""
    doc = inspect.getdoc(obj) or ""
    para = doc.strip().split("\n\n")[0].replace("\n", " ")
    para = re.sub(r":math:`([^`]*)`", lambda m: "@@M@@" + m.group(1) + "@@/M@@", para)
    para = re.sub(r":[a-z]+:`~?([^`]*)`", lambda m: m.group(1).split(".")[-1], para)
    para = para.replace("``", "")
    para = re.sub(r"(?<![*\w])\*([^*]+)\*(?![*\w])", lambda m: "@@E@@" + m.group(1) + "@@/E@@", para)
    para = re.sub(r"(\d+) x (\d+)", lambda m: "@@M@@" + m.group(1) + "\\times " + m.group(2) + "@@/M@@", para)
    para = para.replace(" & ", " and ")
    m = re.match(r"(.+?(?<!e\.g)(?<!i\.e)(?<!et al)(?<!vs)\.)(\s|$)", para)
    s = (m.group(1) if m else para).rstrip(".")
    return s[:160]


def kind(obj) -> str:
    if inspect.isclass(obj):
        return "class"
    if callable(obj):
        return "function"
    return "constant"


def main() -> None:
    out = [
        r"\chapter{API reference}\label{app:api}",
        "",
        r"This appendix lists every public class and function of \code{fuzzyclust}, sub-package by "
        r"sub-package, with the first sentence of its docstring. The lists are generated from the "
        r"\code{\_\_all\_\_} attribute of each module by \code{book/build\_api\_appendix.py}, so they are "
        r"complete by construction; the full signatures, parameters, and attributes are in the online "
        r"documentation and in the docstrings (\code{help(fuzzyclust.cluster.GK)}). The shared constructor "
        r"parameters, fitted attributes, and methods of all clustering estimators are described once in "
        r"\cref{sec:found:api}. The notation of the docstrings is that of \cref{tab:found:notation}.",
        "",
        r"{\footnotesize",
        "% Generated by book/build_api_appendix.py -- do not edit by hand.",
    ]
    for modname, title in SECTIONS:
        mod = importlib.import_module(modname)
        names = list(getattr(mod, "__all__", []))
        out += [
            "",
            rf"\section[\code{{{esc(modname)}}}]{{\code{{{esc(modname)}}}: {esc(title)}}}",
            r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.39\textwidth} l "
            r">{\raggedright\arraybackslash}p{0.43\textwidth}@{}}\toprule",
            r"Name & Kind & Description \\\midrule\endfirsthead",
            r"\toprule Name & Kind & Description \\\midrule\endhead",
            r"\bottomrule\endfoot",
        ]
        for n in names:
            obj = getattr(mod, n)
            if n == "KERNELS":
                desc = r"Names of the kernels accepted by \code{KernelFCM}"
            elif n == "STRATEGIES":
                desc = r"Names of the missing-data strategies of \code{IncompleteFCM} (WDS, PDS, OCS, NPS)"
            elif n == "METHODS":
                desc = r"Names of the spatial methods of \code{SpatialFCM}"
            elif n == "PALETTE":
                desc = r"Fixed categorical color palette; cluster $i$ always gets \code{PALETTE[i]}"
            elif n == "INDEX_DIRECTION":
                desc = r"For every validity index, whether its optimum is the maximum or the minimum"
            elif modname == "fuzzyclust.base" and n == "EPS":
                desc = r"Small constant added to squared distances before negative powers ($10^{-10}$)"
            else:
                desc = (
                    esc(first_sentence(obj))
                    if kind(obj) != "constant"
                    else esc(f"{type(obj).__name__} constant")
                )
            out.append(rf"\code{{{esc(n)}}} & {kind(obj)} & {desc} \\")
        out.append(r"\end{longtable}")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

"""Generate the TikZ artwork of the book cover from a real fuzzyclust run.

Three groups of different shape are clustered with Gustafson--Kessel; every
sample is drawn in the blend of its three membership colors and the membership
landscape is traced by contour lines. The output, ``cover_art.tex``, is a list
of TikZ commands in a coordinate system of centimeters (0..W, 0..H) that
``cover.tex`` and ``banner.tex`` place on the page.

Usage: python book/cover/make_cover_art.py [W H] [output.tex]
"""

from __future__ import annotations

import pathlib
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from fuzzyclust import GK  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent
COLORS = np.array([[58, 154, 217], [240, 123, 63], [43, 192, 142]], float)  # blue, vermilion, green


def data(rng):
    a = rng.multivariate_normal([-1.9, 0.5], [[1.9, 1.15], [1.15, 1.0]], 280)
    b = rng.multivariate_normal([1.6, 1.15], [[0.75, -0.25], [-0.25, 0.9]], 220)
    c = rng.multivariate_normal([0.4, -1.25], [[2.6, 0.3], [0.3, 0.4]], 240)
    return np.vstack([a, b, c])


def main(W=21.6, H=19.0, out=HERE / "cover_art.tex"):
    rng = np.random.default_rng(7)
    X = data(rng)
    gk = GK(n_clusters=3, m=2.0, random_state=3, n_init=5).fit(X)
    # order clusters left -> right so the colors are stable
    order = np.argsort(gk.cluster_centers_[:, 0])
    U = gk.membership_[:, order]
    V = gk.cluster_centers_[order]

    # map data to the art box with a margin, keep the aspect ratio
    lo, hi = X.min(0) - 0.9, X.max(0) + 0.9
    s = min(W / (hi[0] - lo[0]), H / (hi[1] - lo[1])) * 1.08
    cx, cy = (lo + hi) / 2

    def tx(p):
        return (p[..., 0] - cx) * s + W / 2, (p[..., 1] - cy) * s + H / 2 - 0.4

    lines = ["% generated by book/cover/make_cover_art.py -- do not edit"]
    # contour lines of the membership landscape
    gx, gy = np.meshgrid(
        np.linspace(cx - W / s / 2 - 1, cx + W / s / 2 + 1, 360),
        np.linspace(cy - H / s / 2 - 1, cy + H / s / 2 + 1, 330),
    )
    G = np.c_[gx.ravel(), gy.ravel()]
    P = gk.predict_proba(G)[:, order]
    for i in range(3):
        Z = P[:, i].reshape(gx.shape)
        cs = plt.contour(gx, gy, Z, levels=[0.35, 0.5, 0.65, 0.8, 0.92])
        r, g, b = COLORS[i].astype(int)
        for li, segs in enumerate(cs.allsegs):
            op = 0.30 + 0.14 * li
            for seg in segs:
                if len(seg) < 6:
                    continue
                seg = seg[:: max(1, len(seg) // 140)]
                xs, ys = tx(seg)
                pts = " -- ".join(f"({x:.2f},{y:.2f})" for x, y in zip(xs, ys, strict=True))
                color = f"{{rgb,255:red,{r};green,{g};blue,{b}}}"
                lines.append(f"\\draw[line width=0.45pt, draw={color}, draw opacity={op:.2f}] {pts};")
        plt.close("all")
    # samples: color = blend of the membership colors, size grows with certainty
    W2 = U**2 / (U**2).sum(1, keepdims=True)
    cols = W2 @ COLORS
    xs, ys = tx(X)
    for x, y, col, u in zip(xs, ys, cols, U.max(1), strict=True):
        if not (0.1 < x < W - 0.1 and 0.1 < y < H - 0.1):
            continue
        r, g, b = np.clip(col, 0, 255).astype(int)
        rad = 0.045 + 0.05 * u
        color = f"{{rgb,255:red,{r};green,{g};blue,{b}}}"
        opacity = 0.55 + 0.4 * u
        dot = f"({x:.2f},{y:.2f}) circle ({rad:.3f})"
        lines.append(f"\\fill[fill={color}, fill opacity={opacity:.2f}] {dot};")
    # prototypes
    vx, vy = tx(V)
    for x, y in zip(vx, vy, strict=True):
        lines.append(f"\\draw[white, line width=0.8pt] ({x:.2f},{y:.2f}) circle (0.16);")
        lines.append(f"\\fill[white] ({x:.2f},{y:.2f}) circle (0.045);")
    pathlib.Path(out).write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {len(lines)} commands")


if __name__ == "__main__":
    args = sys.argv[1:]
    if len(args) >= 2:
        main(float(args[0]), float(args[1]), *(args[2:3] or [HERE / "cover_art.tex"]))
    else:
        main()

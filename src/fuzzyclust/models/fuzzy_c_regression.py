r"""Fuzzy c-regression models (switching regression) of Hathaway and Bezdek."""

from __future__ import annotations

import numpy as np
from sklearn.utils.validation import check_is_fitted, validate_data

from .._utils import EPS, memberships_from_distances
from ..base import BaseFuzzyClusterer
from .modified_gg import _extend, _require_y, weighted_least_squares


class FuzzyCRegression(BaseFuzzyClusterer):
    r"""Fuzzy c-regression models (FCRM): clusters are regression hyperplanes.

    Instead of a point prototype, every cluster is a linear model
    :math:`y = \mathbf{a}_i^T\mathbf{x} + b_i` and the "distance" of a sample
    :math:`\mathbf{z}_k=[\mathbf{x}_k^T\,y_k]^T` to the cluster is its squared
    residual. FCRM therefore solves the *switching regression* problem: data
    generated by several unknown linear laws, mixed, without knowing which
    sample belongs to which law [1]_. The hyperplanes may cross each other, a
    situation in which clustering of the input–output points with point
    prototypes (FCM, GK) fails.

    Parameters
    ----------
    n_clusters : int, default=2
        Number of regression models :math:`c`.
    m : float, default=2.0
        Fuzziness exponent :math:`m>1`.
    fit_intercept : bool, default=True
    tol : float, default=1e-4
    max_iter : int, default=300
    init : {"random", "kmeans++"} or ndarray, default="random"
        ``"random"`` draws a random fuzzy partition (Hathaway & Bezdek);
        ``"kmeans++"`` seeds point prototypes in the input space; an array is
        an initial partition ``(n_samples, n_clusters)`` or initial centers in
        the input space.
    n_init : int, default=1
        Number of random restarts; the run with the lowest final objective
        :math:`J` is kept (the switching-regression functional has many local
        minima, several restarts are recommended).
    random_state : int, RandomState instance or None, default=None
    verbose : int, default=0

    Attributes
    ----------
    coef_ : ndarray of shape (n_clusters, n_features)
        Slopes :math:`\mathbf{a}_i`.
    intercept_ : ndarray of shape (n_clusters,)
        Offsets :math:`b_i`.
    local_models_ : ndarray of shape (n_clusters, n_features + 1)
        :math:`\boldsymbol\theta_i=[\mathbf{a}_i^T\, b_i]^T`.
    cluster_centers_ : ndarray of shape (n_clusters, n_features)
        Membership-weighted means of the inputs of every cluster (the
        "middle" of the operating region of the local model).
    membership_ : ndarray of shape (n_samples, n_clusters)
    labels_ : ndarray of shape (n_samples,)
    distances_ : ndarray of shape (n_samples, n_clusters)
        Absolute residuals :math:`|y_k - \mathbf{a}_i^T\mathbf{x}_k - b_i|` at convergence.
    objective_, objective_history_, n_iter_
        See :class:`~fuzzyclust.base.BaseFuzzyClusterer`.

    Notes
    -----
    The objective is the c-means functional with the residual distance

    .. math::
        J = \sum_{i=1}^{c}\sum_{k=1}^{N}\mu_{ik}^m E_{ik}(\boldsymbol\theta_i),\qquad
        E_{ik} = \big(y_k - [\mathbf{x}_k^T\,1]\,\boldsymbol\theta_i\big)^2,

    minimized by alternating the weighted least-squares update of the models

    .. math::
        \boldsymbol\theta_i = (\mathbf{X}_e^T\boldsymbol\Phi_i\mathbf{X}_e)^{-1}
        \mathbf{X}_e^T\boldsymbol\Phi_i\mathbf{y},\qquad
        \boldsymbol\Phi_i=\operatorname{diag}(\mu_{i1}^m,\dots,\mu_{iN}^m),

    and the FCM membership update
    :math:`\mu_{ik}=1/\sum_j (E_{ik}/E_{jk})^{1/(m-1)}`.

    Because the distance needs the output, membership of *new* data can only
    be evaluated for input–output pairs: :meth:`predict_proba` takes ``(X, y)``.
    :meth:`predict` returns the outputs of **all** local models, an array of
    shape ``(n_samples, n_clusters)``: a switching regression model does not
    tell which law a new input obeys. To obtain one prediction per sample use
    :class:`~fuzzyclust.models.TakagiSugeno`, whose antecedents partition the
    input space, or the hinging-hyperplane construction of
    :class:`~fuzzyclust.models.HingingHyperplaneTree`.

    References
    ----------
    .. [1] R. J. Hathaway, J. C. Bezdek, "Switching regression models and fuzzy
           clustering", IEEE Trans. Fuzzy Systems, 1(3), 195–204, 1993.

    Examples
    --------
    >>> from fuzzyclust.models import FuzzyCRegression, make_switching_lines
    >>> X, y, lab = make_switching_lines(n_samples=200, random_state=0)
    >>> fcrm = FuzzyCRegression(n_clusters=2, random_state=0).fit(X, y)
    >>> fcrm.coef_.shape, fcrm.intercept_.shape
    ((2, 1), (2,))
    >>> fcrm.predict(X).shape
    (200, 2)
    """

    def __init__(
        self,
        n_clusters: int = 2,
        m: float = 2.0,
        fit_intercept: bool = True,
        tol: float = 1e-4,
        max_iter: int = 300,
        init="random",
        n_init: int = 1,
        random_state=None,
        verbose: int = 0,
    ):
        super().__init__(
            n_clusters=n_clusters,
            m=m,
            tol=tol,
            max_iter=max_iter,
            init=init,
            n_init=n_init,
            random_state=random_state,
            verbose=verbose,
        )
        self.fit_intercept = fit_intercept

    def _check_params(self, X):
        super()._check_params(X)
        if self.m <= 1.0:
            raise ValueError("FuzzyCRegression requires m > 1.")

    def _design(self, X):
        return _extend(X) if self.fit_intercept else X

    def fit(self, X, y=None):
        """Fit the :math:`c` regression models to the pairs ``(X, y)``.

        Parameters
        ----------
        X : array-like of shape (n_samples, n_features)
        y : array-like of shape (n_samples,)
            Required (``None`` raises a ``ValueError``).

        Returns
        -------
        self : object
        """
        _require_y("FuzzyCRegression", y)
        _, y = validate_data(self, X, y, dtype=float, y_numeric=True, ensure_min_samples=2)
        self._y = y
        try:
            super().fit(X)  # validates X again (keeps feature names) and runs the AO loop
        finally:
            del self._y
        return self

    def _init_state(self, X, rng):
        if isinstance(self.init, str) and self.init == "random":
            U = rng.rand(X.shape[0], self.n_clusters)
            return U / U.sum(axis=1, keepdims=True)
        return super()._init_state(X, rng)

    def _update_prototypes(self, X, Um):
        Xe = self._design(X)
        theta = np.stack(
            [weighted_least_squares(Xe, self._y[:, None], Um[:, i])[:, 0] for i in range(self.n_clusters)]
        )
        if self.fit_intercept:
            self.coef_ = theta[:, :-1]
            self.intercept_ = theta[:, -1]
            self.local_models_ = theta
        else:
            self.coef_ = theta
            self.intercept_ = np.zeros(self.n_clusters)
            self.local_models_ = np.hstack([theta, np.zeros((self.n_clusters, 1))])
        s = np.maximum(Um.sum(axis=0), EPS)
        self.cluster_centers_ = (Um.T @ X) / s[:, None]

    def _residuals(self, X, y):
        return y[:, None] - (X @ self.coef_.T + self.intercept_[None, :])

    def _distances(self, X):
        return self._residuals(X, self._y) ** 2

    # ------------------------------------------------------------------ inference
    def _prepare(self, X, y):
        check_is_fitted(self, "coef_")
        if y is None:
            validate_data(self, X, dtype=float, reset=False)
            raise ValueError(
                "FuzzyCRegression needs the output y to evaluate memberships of new data "
                "(the distance of a sample to a regression model is its residual); "
                "use predict(X) for the outputs of the local models."
            )
        X, y = validate_data(self, X, y, dtype=float, y_numeric=True, reset=False)
        return X, y

    def predict_proba(self, X, y=None):
        r"""Memberships of the pairs ``(X, y)`` in the :math:`c` regression models.

        Returns an array of shape ``(n_samples, n_clusters)``.
        """
        X, y = self._prepare(X, y)
        return memberships_from_distances(self._residuals(X, y) ** 2, self.m)

    def predict(self, X):
        """Outputs of **all** local models, ``(n_samples, n_clusters)`` (see Notes)."""
        check_is_fitted(self, "coef_")
        X = validate_data(self, X, dtype=float, reset=False)
        return X @ self.coef_.T + self.intercept_[None, :]

    def predict_labels(self, X, y):
        """Hard assignment of the pairs ``(X, y)`` to the regression model with the smallest residual."""
        return self.predict_proba(X, y).argmax(axis=1)

    def transform(self, X, y=None):
        """Absolute residuals :math:`|y_k-\\hat y_{ik}|` of the pairs ``(X, y)`` w.r.t. every model."""
        X, y = self._prepare(X, y)
        return np.abs(self._residuals(X, y))

    def fit_transform(self, X, y=None, **fit_params):
        return self.fit(X, y).transform(X, y)

    def fit_predict(self, X, y=None, **kwargs):
        """Fit and return the hard labels of the training pairs."""
        return self.fit(X, y).labels_

    def score(self, X, y):
        """Negative objective :math:`-J` of the pairs ``(X, y)``."""
        X, y = self._prepare(X, y)
        d2 = self._residuals(X, y) ** 2
        U = memberships_from_distances(d2, self.m)
        return -self._objective(U**self.m, d2)

    def get_feature_names_out(self, input_features=None):
        check_is_fitted(self, "coef_")
        return np.asarray([f"residual_model_{i}" for i in range(self.n_clusters)], dtype=object)

    def __sklearn_tags__(self):
        tags = super().__sklearn_tags__()
        tags.target_tags.required = True
        return tags


__all__ = ["FuzzyCRegression"]
